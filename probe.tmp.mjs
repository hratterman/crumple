import { chromium } from '@playwright/test';
const b = await chromium.launch({ args: ['--use-gl=angle','--use-angle=swiftshader-webgl','--enable-unsafe-swiftshader','--no-sandbox'] });
const p = await b.newPage({ viewport: { width: 640, height: 360 } });
p.on('console', (m) => { if (m.type() === 'error' || /\[replay\]|\[traffic\]/.test(m.text())) console.log(m.type(), m.text()); });
p.on('pageerror', (e) => console.log('PAGEERR', e.stack));
await p.goto('http://localhost:5377/crumple/?q=low&spawn=highway');
await p.waitForFunction(() => window.__crumple?.ready && window.__crumple.position, null, { timeout: 150000 });
await p.evaluate(() => { window.__crumple.hold = true; window.__crumple.debug.client.input(1, {throttle: 0.8, gearSelect: 1}); });
await p.waitForTimeout(20000);
await p.evaluate(() => { window.__crumple.debug.client.input(1, {throttle: 0, brake: 0.5}); window.__crumple.hold = false; });
const r1 = await p.evaluate(async () => { const r = window.__crumple.replay; const ok = await r.enter(); const s = r.stats; const t = []; const n = r.controller.targets(t); return { ok, st: r.state, bytes: s.bytes, bpf: s.bytesPerFrame, rec: s.recordMs, recMax: s.recordMsMax, targets: n, kinds: t.slice(0, n).map(x => x.kind + ':' + x.valid) }; });
console.log(JSON.stringify(r1));
const r2 = await p.evaluate(() => { const r = window.__crumple.replay; const out = []; for (const f of [0.2, 0.5, 0.8]) { r.seek(r.state.start + f * r.state.duration); out.push(r.stats.lastSeekMs.toFixed(1)); } r.setSpeed(2); r.setDirection(-1); r.play(); return out; });
console.log('seek ms', r2);
await p.waitForTimeout(4000);
await p.evaluate(() => { const r = window.__crumple.replay; r.setDirection(1); r.setSpeed(0.125); });
await p.waitForTimeout(3000);
await p.evaluate(() => { window.__crumple.pinCamera(null); window.__crumple.hold = true; window.__crumple.renderOnce(); });
await p.screenshot({ path: '../traffic-replay.png' });
const r3 = await p.evaluate(async () => { const r = window.__crumple.replay; r.controller.pause(); window.__crumple.hold = false; await r.exit(); return { p: r.pauseHash, q: r.resumeHash, ph: r.state.phase }; });
console.log(JSON.stringify(r3));
await b.close();
