/**
 * Vehicle definition + compiled/runtime contracts — FROZEN (P2).
 *
 * TWO HALVES in one file:
 *  - PURE DATA (VehicleDef, WheelDef, DrivetrainDef, CompiledVehicle, the
 *    wheel node-id rule, WHEEL_DEFAULTS, builder signatures): importable by
 *    main-thread code (render/ui/game) exactly like src/sim/rig/types.ts.
 *  - WORKER RUNTIME (WheelRuntime, DrivetrainState, VehicleRuntime and the
 *    per-tick kernel signatures): worker-only. They reference SimState via
 *    `import type` (erased), so importing this file never pulls sim code
 *    into main; main code must still not USE the runtime types.
 *
 * VEHICLE FRAME (rig-local, authoring convention for every VehicleDef):
 *   up = +Y, forward = −Z, right = +X, left = −X (right-handed, three.js).
 *   A wheel spinning at ω > 0 about its spin axis s (= vehicle LEFT, see
 *   CompiledWheel.spinSign) rolls the car FORWARD. steer +1 = turn right.
 *
 * CANONICAL ORDER of the merged rig (buildVehicleRig/compileVehicle):
 *   nodes = body.nodes (declaration order), then for each wheel in
 *           declaration order: hubI, hubO, rimI[0..n), rimO[0..n),
 *           tireI[0..n), tireO[0..n)          (n = rays; 2 + 4n nodes)
 *   beams = body.beams (declaration order), then for each wheel in
 *           declaration order: WHEEL BEAM ORDER below.
 * Body beams MAY reference generated wheel node ids (suspension arms to
 * `${wheel}.hubI` etc.): ids are resolved after the merge.
 *
 * Units SI. Positions rig-local metres.
 */
