/**
 * Per-tick vehicle step. Phase order (amends canonical rule 3) per object:
 *   vehicle pre-step [estimateWheelOmega (all wheels) → stepDrivetrain →
 *   applyWheelTorques (per wheel, declaration order) → parking clamp → aero]
 *   → steering hydros → applyBeamForces → applyGroundContacts → integrateNodes.
 * Runs before beams, so positions/velocities equal what the ground pass sees
 * this tick (ground normal force evaluated here == this tick's contact force).
 *
 * stepDrivetrain reads `actions` (protocol Action indices), updates engine,
 * clutch, gearbox and diff, computes per-wheel drive + brake torque, calls
 * applyWheelTorques, applies the parking clamp and aero, and writes the
 * cheap telemetry slots into `telemetryOut` (damage is computed only when a
 * snapshot is written). Zero allocation, only + − × ÷ sqrt.
 */
export type StepDrivetrain = (
  state: SimState,
  vehicle: VehicleRuntime,
  actions: Float64Array,
  dt: number,
  telemetryOut: Float32Array,
) => void;

/**
 * Wheel angular velocity estimate (each tick, before torques):
 *   c = (p_hubI + p_hubO)/2, v_c = (v_hubI + v_hubO)/2, s = spinSign·normalize(p_hubO − p_hubI)
 *   for each RIM ring node i (2·rays): ρ_i = (p_i − c) − ((p_i − c)·s)s, t̂_i = s × ρ̂_i
 *   ω = (1/N) Σ ((v_i − v_c)·t̂_i) / |ρ_i|
 * Writes wheel.omega (and contact/load/slip bookkeeping).
 */
export type EstimateWheelOmega = (state: SimState, wheel: WheelRuntime) => void;

/**
 * TORQUE LAW. τ = driveTorque + brake torque (signed, about s; + = forward):
 *   brake: brakeTorque ≥ 0 magnitude; applied τ_b = −brakeTorque·clamp(ω/BRAKE_OMEGA_EPS, −1, 1)
 *          (low-speed clamp: linear ramp, never flips sign chatter; BRAKE_OMEGA_EPS = 1 rad/s).
 *   For each TIRE ring node i (N = 2·rays): F_i = τ / (N·r) · t̂_i, r = wheel.tireRingRadius,
 *   t̂_i = s × ρ̂_i (as in EstimateWheelOmega, ρ from the tire node).
 *   Reaction: hubI and hubO each receive −(Σ F_i)/2 (zero net force: momentum exact).
 *   (No reaction couple on the body in P2, as in RoR.) Detached wheels: drive 0, brakes still act.
 */
export type ApplyWheelTorques = (
  state: SimState,
  wheel: WheelRuntime,
  driveTorque: number,
  brakeTorque: number,
) => void;
export const BRAKE_OMEGA_EPS = 1;
/**
 * Rolling-resistance torque ramp (rad/s): linear below, constant above.
 * 0.1 rad/s (≈ 3 cm/s at the tread) makes it Coulomb-like for a parked
 * car: at 0.5 a neutral, unbraked sedan kept rocking fore-aft (~3 mm,
 * ~9 s period) in the tread-polygon well for > 10 s.
 */
export const ROLL_RES_OMEGA_EPS = 0.1;

/**
 * PARKING CLAMP (fights creep from the regularized μ·tanh(v/0.3) friction).
 * Active when |vehicle speed| < PARK_SPEED and (brake ≥ 0.1 on braked
 * wheels | handbrake ≥ 0.1 on handbrake wheels). For each in-contact tire
 * node i of an active wheel, with ground normal n, tangential ground
 * velocity v_t, node normal force N_i (groundNormalForce, additive export of
 * collision/ground.ts reproducing the kernel's penalty law) and μ = node μ ×
 * material μ:
 *   F_i = −min(PARK_GAIN·m_i/dt·|v_t|, μ·N_i·(1 − tanhR(|v_t|/0.3))) · v̂_t
 * i.e. a capped viscous force whose cap tops ground friction up to exactly μN.
 */
export type ApplyParkingClamp = (
  state: SimState,
  vehicle: VehicleRuntime,
  actions: Float64Array,
  dt: number,
) => void;
export const PARK_SPEED = 0.3;
export const PARK_GAIN = 0.25;

