// ====================================================================== wheels
/**
 * One soft-body wheel (RoR wheels2 structure): 2 hub nodes on the axle, a
 * stiff RIM ring and a soft TIRE ring, each ring made of 2 nodes per ray
 * (inner + outer plane). Everything is GENERATED by buildWheelRig; the body
 * only supplies suspension geometry.
 *
 * Generated geometry (rest pose):
 *   a  = normalize(hubOuter − hubInner)          axle, pointing OUTBOARD
 *   c  = (hubInner + hubOuter) / 2               wheel centre
 *   e1 = normalize(Y × a)  (fallback X × a when |Y × a| < 1e-6)
 *   e2 = a × e1
 *   θk = 2πk / rays,  ρk = cos θk · e1 + sin θk · e2
 *   rimI{k} = c − (width/2)·a + rimRadius·ρk     rimO{k} = c + (width/2)·a + rimRadius·ρk
 *   tireI{k} = c − (width/2)·a + tireRingRadius·ρk, tireO{k} likewise with +,
 *   tireRingRadius = radius − tireNodeRadius (so the contact surface is at `radius`).
 *
 * Mass: hubMass/rimMass/tireMass are WHEEL TOTALS split evenly over the 2
 * hub / 2n rim / 2n tire nodes. MINIMASS (compileVehicle) may raise them.
 */
export interface WheelDef {
  /** Unique among wheels; [A-Za-z0-9_-]+ (no '.'), e.g. 'FL'. Prefix of every generated node id. */
  id: string;
  /** Rig-local axle end positions. hubOuter is the OUTBOARD end. */
  hubInner: Vec3Tuple;
  hubOuter: Vec3Tuple;
  /** 'front' | 'rear': brake bias + telemetry corner (with side from the axle direction). */
  axle: 'front' | 'rear';
  /** Outer tyre radius, m (contact surface). */
  radius: number;
  /** Rim ring radius, m (< radius − tireNodeRadius). */
  rimRadius: number;
  /** Axial distance between the inner and outer ring planes, m. */
  width: number;
  /** Rays per ring: even integer in [10, 14]. */
  rays: number;
  /** Tread ring beams (tireI/tireO neighbours + cross), N/m and N·s/m. */
  tireRingSpring: number;
  tireRingDamp: number;
  /** Rim + axle + hub→rim beams (stiff), N/m and N·s/m. */
  rimSpring: number;
  rimDamp: number;
  /** Rim→tire and hub→tire beams (tyre carcass), N/m and N·s/m. */
  sidewallSpring: number;
  sidewallDamp: number;
  /** Wheel totals, kg. */
  hubMass: number;
  rimMass: number;
  tireMass: number;
  /** Tyre node μ (× material μ). ≈ 2.0 (RoR). Rim nodes use WHEEL_DEFAULTS.rimFriction. */
  friction: number;
  /** Responds to steering (informational: steering is done by body hydro beams). */
  steered: boolean;
  /** Receives drive torque through the differential. */
  driven: boolean;
  /** Service brake on this wheel. */
  braked: boolean;
  /** Max service brake torque at full pedal on the biased axle, N·m (see BrakesDef). */
  brakeTorqueMax: number;
  /** Handbrake acts on this wheel. */
  handbrake: boolean;
  /**
   * Body node ids the hub is bolted to (knuckle / upright). For each id, in
   * list order, buildWheelRig emits beams hubI–id then hubO–id. Their break
   * force decides when the wheel tears off. May be empty when body beams
   * reference the hub nodes directly.
   */
  attach: string[];
  /** Optional overrides (defaults in WHEEL_DEFAULTS). */
  tireNodeRadius?: number;
  /**
   * Tread contact layer stiffness per tyre node, N/m (RigNodeDef.contactSpring
   * of the generated tire nodes; 0 = rigid-contact law). Additive P2 field.
   */
  tireContactSpring?: number;
  /**
   * Rolling resistance coefficient C_rr (additive P2 field, default 0):
   * a torque −C_rr·load·rollRadius·clamp(ω/ROLL_RES_OMEGA_EPS, −1, 1)
   * about the axle (tyre hysteresis the viscous carcass lacks at low speed).
   */
  rollingResistance?: number;
  /**
   * Tread BRUSH model (additive P2 field): > 0 marks the tyre nodes `tread`
   * (ground kernel: normal force only) and gives each in-contact tread node
   * a brush deflection driven by the RIGID-wheel slip velocity at its
   * contact point, force −k·δ − c·u capped at μN (see wheels.ts
   * applyTreadBrush). N/m per tread node; 0 = node-level implicit friction.
   */
  treadBrushStiffness?: number;
  /** Brush damping on the rigid-wheel slip velocity, N·s/m per tread node. */
  treadBrushDamping?: number;
  /**
   * Hoop tension, 0..1 (additive P2 fields, default 0): the fraction of the
   * rim / tread rings' centripetal load carried as ring-segment tension (a
   * rim and a belted tyre do not balloon with speed; see wheels.ts
   * applyHoopTension).
   */
  rimHoopTension?: number;
  treadHoopTension?: number;
  /**
   * R-PHYS tyre model (tyre.ts; additive, optional — defaults keep the P2
   * tyre): load sensitivity of μ per unit of relative load (0 = none),
   * sliding/peak μ ratio (1 = no fall-off), the combined slip σ where the
   * fall-off starts / completes, and the rolling-loss correction table
   * (excess loss per unit load every 10 km/h of tread speed, from 0).
   */
  tyreLoadSensitivity?: number;
  tyreSlideRatio?: number;
  tyrePeakSlip?: number;
  tyreSlideSlip?: number;
  rollingLossComp?: readonly number[];
  /** Design load Fz0 of the load sensitivity, N (default: the car's weight shared over its wheels). */
  tyreDesignLoad?: number;
  /** Lateral / longitudinal peak friction ratio μ_y/μ_x applied to the tread brush cap (default 1). */
  tyreLateralMu?: number;
  /**
   * R-TYRE (additive, optional): lateral stiffness of the CARCASS between the
   * rim and the contact patch, N/m at the cold inflation pressure (0 / absent =
   * rigid, the P2–R-PHYS tyre). In series with the tread brush it sets the
   * relaxation length σ_α ≈ C_α/C_y (wheels.ts applyTreadBrush). Passenger
   * radials ≈ 1.5–2.5e5 N/m (Pacejka 2012 §7: σ_α ≈ 0.3–0.6 m).
   */
  tyreLateralStiffness?: number;
  /**
   * R-TYRE (additive, optional): cold inflation (gauge) kPa at 25 °C (default
   * 230), compound grip window (tyreThermal.ts TYRE_COMPOUNDS: 'road' default,
   * 'performance', 'truck') and new tread depth, mm (default 8).
   */
  tyrePressure?: number;
  tyreCompound?: 'road' | 'performance' | 'track' | 'truck';
  tyreTreadDepth?: number;
  /**
   * R-PHYS (additive): share of the brake reaction couple's hub force taken by
   * hubI (the caliper bracket's inboard bias), 0..1, default 0.5. Sets the
   * brake compliance steer of the beam upright (wheels.ts applyUprightReaction).
   */
  caliperInboard?: number;
  /**
   * R-PHYS (additive): brake disc (or drum) mass, kg, for the disc
   * temperature / pad fade model (brakeHeat.ts). Default brakeTorque / 300
   * N·m per kg (a 2500 N·m front caliper ↔ an 8.3 kg disc).
   */
  brakeDiscMass?: number;
  /** R-PHYS (additive): ventilated disc (cools faster at speed). Default: front axle true, rear false. */
  brakeDiscVented?: boolean;
  attachSpring?: number;
  attachDamp?: number;
  attachBreakF?: number;
}

