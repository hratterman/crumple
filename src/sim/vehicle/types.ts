/** Generated wheel node parts. */
export type WheelNodePart = 'hubI' | 'hubO' | 'rimI' | 'rimO' | 'tireI' | 'tireO';

/**
 * Wheel node id rule — FROZEN. Hubs: `${wheelId}.hubI`, `${wheelId}.hubO`;
 * ring nodes: `${wheelId}.rimI${k}`, `.rimO${k}`, `.tireI${k}`, `.tireO${k}`
 * with k = 0..rays−1 (no padding). E.g. 'FL.hubO', 'RR.tireI7'.
 */
export function wheelNodeId(wheelId: string, part: WheelNodePart, k?: number): string {
  return part === 'hubI' || part === 'hubO' ? `${wheelId}.${part}` : `${wheelId}.${part}${k ?? 0}`;
}

/**
 * WHEEL BEAM ORDER — FROZEN (amended P2: 22 per ray, X-braced diagonals).
 * Per wheel (k1 = (k + 1) mod n):
 *   1. attach: for each id in `attach`: hubI–id, hubO–id      (attachSpring/Damp/BreakF, type normal)
 *   2. axle:   hubI–hubO                                       (rim params)
 *   3. per ray k = 0..n−1, 22 beams in this order:
 *       rim  (rim params):      hubI–rimI{k}, hubO–rimO{k}, hubI–rimO{k}, hubO–rimI{k},
 *                               rimI{k}–rimO{k}, rimI{k}–rimI{k1}, rimO{k}–rimO{k1}, rimI{k}–rimO{k1}½
 *       tread (tireRing):       tireI{k}–tireI{k1}, tireO{k}–tireO{k1}, tireI{k}–tireO{k}, tireI{k}–tireO{k1}½
 *       sidewall (sidewall):    rimI{k}–tireI{k}, rimO{k}–tireO{k}, rimI{k}–tireI{k1}, rimO{k}–tireO{k1},
 *                               rimI{k1}–tireI{k}, rimO{k1}–tireO{k}, hubI–tireO{k}, hubO–tireI{k}
 *       X-brace:                rimO{k}–rimI{k1}½ (rim params), tireO{k}–tireI{k1}½ (tireRing params)
 *   ½ = half spring AND damping (each quad is X-braced with two half-stiffness
 *   diagonals: per-node Σk is unchanged and the wheel is achiral — one-way
 *   diagonals made left/right wheels crab the same way under torque).
 * Beam count per wheel = 2·attach.length + 1 + 22·rays. All type 'normal'.
 */
export const WHEEL_BEAMS_PER_RAY = 22;
export const WHEEL_RAYS_MIN = 10;
export const WHEEL_RAYS_MAX = 16;

// ====================================================================== drivetrain
export type DiffType = 'open' | 'locked' | 'limited' | 'viscous';

/**
 * Engine + clutch + gearbox + one differential across ALL driven wheels.
 *
 * Model (drivetrain agent implements; this is the contract):
 *  - Engine: dω_e/dt = (T_eng − T_clutch) / engineInertia, rpm = ω_e·60/2π.
 *    T_eng = throttle·LUT(rpm) − (1 − throttle)·engineBrakeTorque·clamp(rpm/redlineRpm, 0, 1);
 *    an idle governor raises effective throttle below idleRpm; the rev limiter
 *    cuts throttle at revLimitRpm (hysteresis ~200 rpm).
 *  - Gearbox input ω_g = ratio(gear)·finalDrive·mean(ω of driven, attached wheels).
 *  - Clutch: |T_clutch| ≤ clutchMaxTorque·(1 − clutchApplied); slipping when
 *    ω_e ≠ ω_g. Auto-clutch: disengaged near/below idle with low throttle and
 *    during shifts; applied = max(pedal, auto).
 *  - Wheel drive torque total = T_clutch·ratio·finalDrive, split by the diff:
 *    open = equal split; locked = equalizes driven-wheel ω (stiff coupling);
 *    limited = open + transfer ∝ Δω capped at diffLockTorque. Detached wheels get 0.
 *  - Auto mode: up at autoShiftUpRpm, down at autoShiftDownRpm; each shift
 *    disengages the clutch for shiftTimeS.
 */
export interface DrivetrainDef {
  /** (rpm, N·m) points, rpm strictly ascending, ≥ 2 points. Sampled to a LUT at compile. */
  torqueCurve: [number, number][];
  idleRpm: number;
  redlineRpm: number;
  revLimitRpm: number;
  /** kg·m² (crank + flywheel). */
  engineInertia: number;
  /** N·m drag at redline with zero throttle. */
  engineBrakeTorque: number;
  /** Forward ratios, gear 1 first (positive). */
  gearRatios: number[];
  /** Reverse ratio MAGNITUDE (positive); the sign is applied internally. */
  reverseRatio: number;
  finalDrive: number;
  shiftTimeS: number;
  autoShiftUpRpm: number;
  autoShiftDownRpm: number;
  diff: DiffType;
  /** 'limited' only: max transferred torque, N·m. */
  diffLockTorque?: number;
  /** N·m the fully engaged clutch can carry. */
  clutchMaxTorque: number;
  /** Initial transmission mode. Default 'auto'. */
  transmission?: TransmissionMode;
  /**
   * Traction control (additive P2): target driven-wheel slip ratio (e.g.
   * 0.1). Throttle is cut while the fastest driven wheel's rolling speed
   * exceeds the undriven wheels' by more than that ratio. 0/absent = off.
   */
  tractionControl?: number;
  /**
   * R-PHYS (additive, optional): where the drive torque's reaction goes.
   * 'body' (default): the differential is on the body (independent rear,
   * transaxle) — a pure couple on the body's frame nodes. 'axle': a live
   * axle — the couple acts on each driven wheel's upright / axle housing.
   */
  driveReaction?: 'body' | 'axle';
  /** R-PHYS (additive, optional): engine systems spec (engineSystems.ts: fuel, cooling, oil, stall). */
  engine?: EngineDef;
  /**
   * R-PHYS (additive, optional): clutch-pack (Salisbury) limited-slip model for diff 'limited'. Locking
   * torque = preload + ramp·|T_in| (power ramp when the diff is driven, coast ramp on the overrun), so the
   * torque bias ratio is (1 + r)/(1 − r) once the preload is overcome (Milliken RCVD ch. 20). Without it,
   * 'limited' keeps the constant diffLockTorque.
   */
  lsd?: { preload: number; powerRamp: number; coastRamp: number };
  /**
   * R-PHYS (additive, optional): torsional strength of each driven halfshaft / CV joint, N·m at the wheel;
   * an overload snaps it (DrivetrainStateEx.shaftBroken). Absent = unbreakable.
   */
  halfshaftBreakTorque?: number;
  /** R-PHYS (additive, optional): viscous coupling coefficient for diff 'viscous', N·m per rad/s of wheel-speed difference. */
  viscousCoeff?: number;
  /** R-PHYS (additive, optional): electronic top-speed governor, km/h (throttle faded out over the last 7 km/h). */
  speedLimitKmh?: number;
}

/** R-PHYS: engine systems spec. Defaults: displacement from the peak torque (≈ 110 N·m/L), petrol, 60 L tank, 75 % full. */
export interface EngineDef {
  displacementL: number;
  fuel?: 'petrol' | 'diesel';
  tankL?: number;
  /** Fuel at spawn / repair, L (default 0.75 × tankL). */
  startFuelL?: number;
  /** Crank orientation (engine rock axis): default transverse for front-wheel drive, else longitudinal. */
  layout?: 'longitudinal' | 'transverse';
  /** Engine rock (the powertrain reactions on the engine mounts, runtime.ts applyEngineReaction); default true. */
  rock?: boolean;
}

export type TransmissionMode = 'auto' | 'manual';

/**
 * Service brake bias. Per-wheel torque at full pedal:
 *   brakeTorqueMax · axleFactor, axleFactor = bias_axle / max(frontBias, 1 − frontBias),
 *   bias_front = frontBias, bias_rear = 1 − frontBias (biased axle reaches brakeTorqueMax).
 * Handbrake: handbrake · handbrakeTorqueMax on wheels with `handbrake: true`;
 * a wheel gets max(service, handbrake) torque.
 */
export interface BrakesDef {
  /** 0..1, fraction toward the front axle (≈ 0.6–0.7). */
  frontBias: number;
  handbrakeTorqueMax: number;
  /**
   * R-PHYS (additive, optional): the car has ABS (with EBD) / ESC fitted
   * (brakes.ts). Default false. Toggled at runtime by `setAssists`.
   */
  abs?: boolean;
  esc?: boolean;
}

/**
 * Quadratic aero on COM velocity v (ρ = 1.225 kg/m³), distributed over BODY
 * nodes proportional to mass: drag = −½ρ·dragCoeffArea·|v|·v;
 * lift = +½ρ·liftCoeffArea·|v|²·up_vehicle (negative liftCoeffArea = downforce).
 */
export interface AeroDef {
  /** Cd·A, m². */
  dragCoeffArea: number;
  /** Cl·A, m² (positive = lift). */
  liftCoeffArea: number;
  /**
   * R-PHYS (additive, optional): lift split per axle, Cl·A at the front / rear axle, m² (+ = lift). When
   * either is set the lift acts at the axles (liftCoeffArea is then ignored): a uniform part plus a pitch
   * couple, so the front axle unloads by ½ρv²·liftFront and the rear by ½ρv²·liftRear.
   */
  liftFront?: number;
  liftRear?: number;
}

/** Body node ids defining the vehicle frame (camera, telemetry speed, recover). */
export interface VehicleFrameDef {
  /** Reference point near the COM. */
  origin: string;
  /** forward = normalize(front − origin) ≈ −Z at rest. */
  front: string;
  /** up = normalize(top − origin) orthogonalized against forward ≈ +Y at rest. */
  top: string;
}

export interface SteeringDef {
  /** Road-wheel angle at |steer| = 1, degrees (HUD/AI/camera estimate; physics = hydros). */
  maxWheelAngleDeg: number;
}

/**
 * Full vehicle definition: plain JSON, structured-cloneable (posted in
 * `spawnVehicle`). STEERING: every `hydro` beam in `body` is a steering
 * hydro driven by the `steer` action (rest = base·(1 + hydroTravel·steer),
 * engine hydro pass, unchanged from P1); author hydroTravel signs so that
 * steer +1 turns right.
 */
export interface VehicleDef {
  name: string;
  /** Chassis/structure/suspension. May reference generated wheel node ids in beams. */
  body: RigDef;
  /** Declaration order = node/beam order. 4-wheel cars declare FL, FR, RL, RR. */
  wheels: WheelDef[];
  drivetrain: DrivetrainDef;
  brakes: BrakesDef;
  aero: AeroDef;
  steering: SteeringDef;
  frame: VehicleFrameDef;
  /**
   * Feel pass (additive, optional): the rigid shell cluster (shell.ts) over
   * the body shell groups; false disables it. Default: SHELL_GROUPS with the
   * shell.ts defaults.
   */
  shell?: ShellDef | readonly ShellDef[] | false;
  /**
   * R-CRASH (additive, optional): unloading stiffness multiple α of the body's crush-yielded members
   * (beams.ts CRUSH_UNLOAD_*). Default CRUSH_UNLOAD_DEFAULT; 1 = off (plain elastic unloading).
   */
  crushUnload?: number;
  /** R-CRASH: the same for HELD / never-yielding members (temporary offset). Default crushUnload; 1 = off. */
  crushUnloadHeld?: number;
  /**
   * R-CRASH: node-id patterns (`*` = any suffix) of the SET members — body beams with both ends matching
   * unload permanently once crash loaded (≥ CRUSH_TRIGGER_SET × their yield force), yielded or not: the
   * roof and pillars, whose real steel is at yield under the loads that bend the stability-capped lattice
   * (roof strength / rollover; roofStrength.ts). Default none.
   */
  crushSet?: readonly string[];
  /**
   * R-PHYS (additive, optional): asymmetric digressive dampers on the shock
   * beams (dampers.ts), per axle; a shock beam belongs to the axle of the
   * wheel whose hub is nearest. Omitted: linear symmetric d·v (pre-R-PHYS).
   */
  dampers?: VehicleDampersDef;
}

/** R-PHYS: per-axle damper characteristics (dampers.ts DamperDef; `true` = DAMPER_DEFAULTS). */
export interface VehicleDampersDef {
  front?: DamperCurveDef | true;
  rear?: DamperCurveDef | true;
}

/** R-PHYS: see dampers.ts (bump / rebound low-speed rates as fractions of d, digressive knee m/s, high-speed slope fraction). */
export interface DamperCurveDef {
  bump?: number;
  rebound?: number;
  kneeSpeed?: number;
  highSpeedRatio?: number;
}

