#!/usr/bin/env bash
# Builds the R-CORE physics kernel (src/sim/wasm/kernel.c) into
#   src/sim/wasm/kernel-scalar.wasm   wasm32, no SIMD
#   src/sim/wasm/kernel-simd.wasm     wasm32 + simd128
#   src/sim/wasm/binary.ts            both, base64 (what the worker bundle imports)
# Reproducible: same clang 18 / wasm-ld 18 → byte-identical output (CI rebuilds
# and diffs). Toolchain: CLANG / WASM_LD env vars, default clang-18 or clang.
set -euo pipefail
cd "$(dirname "$0")/.."

CLANG="${CLANG:-$(command -v clang-18 || command -v clang)}"
DIR=src/sim/wasm
SRC=$DIR/kernel.c

# -ffp-contract=off: no fused multiply-add (bit-identity with the JS kernel).
# No -ffast-math: IEEE semantics, no reassociation.
COMMON=(--target=wasm32-unknown-unknown -O3 -nostdlib -ffreestanding -fno-builtin-memset
  -ffp-contract=off -fno-exceptions -Wall -Wextra -Werror
  -Wl,--no-entry -Wl,--import-memory -Wl,--export=__heap_base
  -Wl,-z,stack-size=65536 -Wl,--stack-first -Wl,--strip-all)

"$CLANG" "${COMMON[@]}" -mno-simd128 -o $DIR/kernel-scalar.wasm $SRC
"$CLANG" "${COMMON[@]}" -msimd128 -DCRUMPLE_SIMD -o $DIR/kernel-simd.wasm $SRC

node - "$DIR" <<'JS'
const fs = require('node:fs');
const dir = process.argv[2];
const b64 = (f) => fs.readFileSync(`${dir}/${f}`).toString('base64');
const out = `// GENERATED by tools/build-wasm.sh from kernel.c — do not edit.
// The R-CORE kernel binaries, base64 (the worker imports this module lazily).
export const KERNEL_SCALAR_WASM = '${b64('kernel-scalar.wasm')}';
export const KERNEL_SIMD_WASM = '${b64('kernel-simd.wasm')}';
`;
fs.writeFileSync(`${dir}/binary.ts`, out);
JS
ls -l $DIR/*.wasm
